import { ROLES } from "@/lib/constants";

/**
 * Вкладки раздела «Аналитика».
 *
 * Календарь — вещь тяжёлая: он читает заявки, партии, отгрузки и оплаты и
 * показывает их по дням. Владелец просил не перегружать им общую страницу,
 * поэтому это отдельная вкладка и только у администратора: остальным ролям
 * нужен свой разрез, а не вся жизнь хозяйства подряд.
 *
 * У остальных вкладок нет — одна вкладка в ряду выглядит как недоделка.
 *
 * **Календарь стоит первым** — так решил владелец, посмотрев на него в работе.
 * Отчёт отвечает на вопрос «сколько за тридцать дней», календарь — «а что было
 * во вторник», и второй вопрос задают чаще: с него начинают разбираться, когда
 * что-то пошло не так. Раздел открывается на нём же (`/analytics` показывает
 * календарь), а отчёт лежит соседней вкладкой.
 */
export function analyticsTabsFor(role: string | null | undefined) {
  // «Итоги месяца» (02.11.2026, владелец: «мощная аналитика по продажам, срезу и другим показателям за месяц») —
  // владельцу и РОПу.
  if (role === ROLES.SALES_HEAD) {
    return [
      { href: "/analytics", label: "Аналитика хозяйства" },
      { href: "/analytics/month", label: "Итоги месяца" },
    ];
  }
  if (role !== ROLES.ADMIN) return [];
  return [
    { href: "/analytics/month", label: "Итоги месяца" },
    { href: "/analytics/calendar", label: "Календарь" },
    { href: "/analytics", label: "Отчёт" },
  ];
}
