import { ROLES } from "@/lib/constants";

/**
 * Вкладки раздела «Аналитика».
 *
 * Календарь — вещь тяжёлая: он читает заявки, партии, отгрузки и оплаты и
 * показывает их по дням. Владелец просил не перегружать им общую страницу,
 * поэтому это отдельная вкладка и только у администратора: остальным ролям
 * нужен свой разрез, а не вся жизнь хозяйства подряд.
 *
 * У остальных вкладок нет — одна вкладка в ряду выглядит как недоделка.
 */
export function analyticsTabsFor(role: string | null | undefined) {
  if (role !== ROLES.ADMIN) return [];
  return [
    { href: "/analytics", label: "Отчёт" },
    { href: "/analytics/calendar", label: "Календарь" },
  ];
}
