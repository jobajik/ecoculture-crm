/** Вкладки цифр у владельца и РОПа: одна страница цифр, рейтинг, календарь (владельцу) и архив. У остальных ролей вкладок нет. */
export function analyticsTabsFor(role: string | null | undefined) {
  if (role !== ROLES.ADMIN && role !== ROLES.SALES_HEAD) return [];
  const tabs: { href: string; label: string; match?: string[] }[] = [
    { href: "/analytics/flow", label: "Цифры за период", match: ["/analytics/flow"] },
    { href: "/sales", label: "Рейтинг и бонусы", match: ["/sales"] },
  ];
  // Календарь читает заявки, партии, отгрузки и оплаты по дням — вещь тяжёлая, она только у владельца.
  if (role === ROLES.ADMIN) tabs.push({ href: "/analytics/calendar", label: "Календарь", match: ["/analytics/calendar"] });
  tabs.push({ href: "/analytics/archive", label: "Архив отчётов", match: ["/analytics/archive", ...ARCHIVED_REPORTS.map((r) => r.href)] });
  return tabs;
}
