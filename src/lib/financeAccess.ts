import { ROLES } from "./constants";

/**
 * Кто видит деньги и кто их трогает.
 *
 * Владелец попросил: «добавь отслеживание оплат для РОПа, без права изменений.
 * Просто чтобы видела долги и прочее». До этого раздел «Оплаты» был закрыт от
 * РОПа целиком, и выходило странно: человек отвечает за план продаж, а узнать,
 * заплатили ли по его заявкам, может только спросив бухгалтера.
 *
 * Отсюда ДВА разных права, и путать их нельзя:
 *
 * - **видеть** — бухгалтер, администратор и РОП;
 * - **трогать** (проводить оплату, отмечать счёт, ставить обещание, решать
 *   рекламацию) — только бухгалтер и администратор.
 *
 * Почему РОПу не дать и второе, раз он всё равно видит: у одной записи должна
 * быть одна дверь. Разреши двоим проводить деньги — и за неразнесённую оплату
 * спросить будет не с кого, а расхождение с кассой придётся разбирать по
 * памяти. Тот же довод, по которому отметку о счёте ставит только бухгалтер.
 *
 * Функции чистые и покрыты `scripts/check-finance-access.ts`.
 */

/** Кто открывает раздел «Оплаты». */
export function canSeeFinance(role: string | null | undefined): boolean {
  return role === ROLES.ACCOUNTANT || role === ROLES.ADMIN || role === ROLES.SALES_HEAD;
}

/** Кто в нём что-то МЕНЯЕТ: проводит деньги, отмечает счёт, ставит обещание. */
export function canEditFinance(role: string | null | undefined): boolean {
  return role === ROLES.ACCOUNTANT || role === ROLES.ADMIN;
}

/**
 * Разделы внутри «Оплат», которые РОПу не нужны: удержания с сотрудников —
 * кадровая история, журнал — служебный след действий бухгалтера.
 */
export function canSeeFinanceInternals(role: string | null | undefined): boolean {
  return role === ROLES.ACCOUNTANT || role === ROLES.ADMIN;
}
