// Телефон — в одном виде везде: «+77015552030». Без пробелов, скобок и
// дефисов, всегда с +7; «8 701 …» превращается в «+7701…».
//
// Владелец, 01.10.2026: «нужна маска телефона (+7 всегда выходило) и если
// добавляют с 8, то исправляешь. Удаляешь все пробелы и прочее. Чтобы была одна
// форма». Поле ввода (`PhoneInput`) правит номер прямо при наборе, запись в
// таблицу (`repo/clients`, `repo/leads`, `repo/orders`) — ещё раз на сервере.
// Проверка — `scripts/check-phone.ts`. Модуль без сети: его зовут и страницы.
// ---------------------------------------------------------------------------

/**
 * Номер к виду «+7XXXXXXXXXX». «8 701 555 20 30», «+7 (701) 555-20-30»,
 * «7015552030» → «+77015552030». Не похоже на номер с +7 (иностранный,
 * неполный, «нет») — без изменений, только по краям обрезаны пробелы.
 */
export function formatPhone(raw: string | null | undefined): string {
  const text = String(raw ?? "").trim();
  const d = text.replace(/\D/g, "");
  if (d.length === 11 && (d[0] === "7" || d[0] === "8")) return `+7${d.slice(1)}`;
  if (d.length === 10 && !text.startsWith("+")) return `+7${d}`;
  return text;
}

/** Номер полный: +7 и десять цифр. */
export function phoneComplete(value: string | null | undefined): boolean {
  return /^\+7\d{10}$/.test(String(value ?? ""));
}

/**
 * Маска при наборе: что показать в поле после правки `next` (было `prev`).
 * Всегда «+7» и не больше десяти цифр после него; восьмёрка в начале — это
 * «8 701…», она становится +7. Вставили номер целиком в любом виде — он
 * разбирается так же.
 */
export function maskPhoneInput(next: string, prev = ""): string {
  let d = String(next ?? "").replace(/\D/g, "");
  if (!d) return "";
  const pasted = d.length - String(prev ?? "").replace(/\D/g, "").length > 1;
  // Вставили «+7 701 …» в поле, где уже стояло «+7», — лишнее спереди.
  if (pasted && d.length > 11) d = d.slice(-11);
  if (pasted && d.length === 10) d = `7${d}`;
  if (d[0] === "8") d = `7${d.slice(1)}`;
  else if (d[0] !== "7") d = `7${d}`;
  // В поле уже «+7», а набирают «8 701…» — эта восьмёрка не цифра номера.
  if (d[1] === "8") d = `7${d.slice(2)}`;
  return `+${d.slice(0, 11)}`;
}
