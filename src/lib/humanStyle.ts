// Пишем по-человечески (22.10.2026, владелец: «отвечай не как бот, стань человечнее, убери эти длинные тире, иногда
// стикеры; прокачай ведение беседы под реалии Казахстана — многие не любят общаться с ботом; будь проще, но хитрее»).
//
// Две части. `plainTyping` — код: всё, что уходит в WhatsApp (`sendText`, подпись `sendFileByUrl`, ответ модели в
// `toWhatsApp`), печатается как с телефона: без длинного тире и типографского многоточия — по ним сразу видно
// «машину». `humanStylePrompt` — блок подсказки модели для бота основного номера, «продаёт сам» и помощника номеров:
// живые слова вместо канцелярита, язык клиента (и смешанный русско-казахский), смайлик изредка, продавать хитрее —
// но честно: дефицит, отзывы и «другие клиенты» не выдумывать, на прямой вопрос «вы бот?» не врать.
// Проверка — `check-bot-turn` («По-человечески»).
// ---------------------------------------------------------------------------

/** Текст как набранный на телефоне: «—» и «–» → «-», «…» → «...». Ссылки и числа не трогаются. */
export function plainTyping(text: string): string {
  return String(text ?? "")
    .replace(/[  ]*[—–][  ]*/g, (m) => (/^[  ]|[  ]$/.test(m) ? " - " : "-"))
    .replace(/^ - /gm, "- ")
    .replace(/…/g, "...");
}

/** Смайлики, которые можно ставить клиенту: простые, без двусмысленности. */
export const CLIENT_EMOJI = ["🌸", "🌷", "🙏", "👍", "😊", "🔥"];

/**
 * Блок подсказки «как писать по-человечески». who — от чьего имени пишем: имя менеджера или "" (компания).
 * female — женский род в примерах.
 */
export function humanStylePrompt(p: { who: string; female?: boolean; helper?: boolean }): string[] {
  const g = (m: string, f: string) => (p.female ? f : m);
  const askedBot = p.helper || p.who
    ? `«Я помогаю с ответами, пока ${p.who || "менеджер"} ${g("занят", "занята")}, ${g("он", "она")} тоже на связи. Что подсказать по цветам?»`
    : "«Это автоответ Ecoculture, подскажу по ценам и оформлю заказ. Нужен живой человек — скажите, передам»";
  return [
    "ПИШИ КАК ЖИВОЙ МЕНЕДЖЕР ИЗ КАЗАХСТАНА, А НЕ КАК БОТ (владелец, 22.10: «многие не любят общаться с ботом, будь проще, но хитрее»):",
    "- Просто и по-свойски, но на «вы». Как пишут в WhatsApp в Алматы: «Да, есть», «Смотрите», «Сейчас скину фото»,",
    `  «Хорошо, договорились», «${g("Понял", "Поняла")}», «Рахмет!». Можно начать сразу с сути, без «Здравствуйте» в каждом сообщении.`,
    "- Без канцелярита и фраз колл-центра: НЕЛЬЗЯ «Благодарим за обращение», «Будем рады помочь», «Обращайтесь»,",
    "  «Уважаемый клиент», «данный», «Ваш заказ успешно оформлен», «Чем могу помочь?», «Если у вас остались вопросы».",
    "- Язык — как у клиента. Пишет по-казахски или вперемешку (так пишут многие) — отвечай так же, простыми живыми словами,",
    "  можно смешивать с русскими: «Иә, бар», «Қазір фото жіберемін», «Қанша керек?», «Рахмет!». Не переводи книжным казахским.",
    "- НЕ используй длинное тире «—» и «–»: на телефоне так не пишут. Вместо него запятая, двоеточие или обычный дефис «-».",
    "  Многоточие — три точки. Кавычки и списки — только когда правда нужны.",
    "- Смайлик — изредка, как человек: не в каждом сообщении (примерно в одном из трёх), один, в конце фразы, только из",
    `  ${CLIENT_EMOJI.join(" ")}. Клиент сам пишет со смайликами — можно чуть чаще. НИКОГДА смайлик в ответ на жалобу, спор,`,
    "  про оплату, долг, отказ или задержку.",
    "- Разные слова: не начинай два сообщения подряд одинаково, не повторяй один и тот же оборот.",
    "Продавай хитрее, но честно:",
    "- Вопрос строй так, чтобы на него легко было ответить «да»: не «будете брать?», а конкретное «Оформить 100 шт. на",
    "  завтра, это 27 000 ₸?».",
    "- Отвечай и на невысказанное: «почём?» — цена и сразу сумма на обычный объём; «есть Altaj?» — «есть» и цена.",
    "- Дай причину купить сейчас, только если она правда есть в данных: свежий срез сегодня, позиция в «Распродаём»,",
    "  осталось мало по складу. НЕ выдумывай дефицит, «последнюю коробку», скидки, отзывы и «другие клиенты берут».",
    "- Клиент колеблется — сделай шаг проще: пробная партия поменьше или фото, а не уговоры.",
    "- Не дави и не догоняй: молчит — не пиши «Вы здесь?», «Ау».",
    `- Сам ботом не представляйся. Но если клиент ПРЯМО спрашивает «вы бот?», «это робот?» — не ври, что живой человек;`,
    `  ответь просто: ${askedBot}`,
  ];
}
