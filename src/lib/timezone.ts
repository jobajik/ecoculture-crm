/**
 * Часовой пояс сервера — Алматы.
 *
 * Vercel запускает приложение по Гринвичу. Все «сегодня» в коде собираются из
 * `getFullYear()/getMonth()/getDate()` — то есть по часам сервера, — и с полуночи
 * до пяти утра по Алматы программа жила во вчерашнем дне: платёж «сегодняшним
 * числом» отклонялся как платёж из будущего, лист сборки открывался на вчера,
 * правило «удалить можно только сегодняшний платёж» считало не тот день. Мест
 * таких два десятка, и чинить каждое значило бы забыть одно.
 *
 * Node подхватывает смену `process.env.TZ` на лету, поэтому достаточно
 * выставить её до первого расчёта даты. Модуль импортируется из `auth.ts` и
 * `sheets.ts` — через них проходит любой серверный запрос. Браузер живёт по
 * часам телефона, и там это не нужно.
 */
export const APP_TIME_ZONE = "Asia/Almaty";

if (typeof process !== "undefined" && process.env && process.env.TZ !== APP_TIME_ZONE) {
  process.env.TZ = APP_TIME_ZONE;
}

/** Сегодня (или день даты) по местному времени, «ГГГГ-ММ-ДД». */
export function localDayKey(d: Date = new Date()): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
