// --- Что программа передала в черновике -------------------------------------------------------------------

const digits = (s: string) => s.replace(/[^\d]/g, "");
/** «180 ₸», «1 250 тг», «2 550 тенге» — цена; пробелы внутри числа (в том числе неразрывные) не мешают. */
const PRICE = /(\d[\d\s  ]*)(?:[.,]\d+)?\s*(?:₸|тг(?![а-яё])|тенге)/giu;
/** «200 шт.», «50 штук» — количество. */
const QTY = /(\d[\d\s  ]*)\s*(?:шт(?![а-яё])|штук)/giu;
/** Строка-позиция черновика: «• Роза Jumilia, 50 см — *180 ₸*». */
const BULLET = /^\s*[•·▪*-]\s+\S/;
/** Латиница — так у нас записаны сорта (Jumilia, Altaj, Alissa 1 Pure White). */
const LATIN = /[A-Za-z][A-Za-z'’.-]*(?:\s+(?:[A-Za-z][A-Za-z'’.-]*|\d{1,2}(?=\s+[A-Za-z])))*/g;
const NOT_A_VARIETY = new Set(["ecoculture", "whatsapp", "kaspi", "kaspi pay", "ok", "crm", "pdf"]);

const allMatches = (re: RegExp, text: string): string[] => {
  const out: string[] = [];
  for (const m of text.matchAll(new RegExp(re.source, re.flags))) {
    const d = digits(m[1]);
    if (d) out.push(d);
  }
  return out;
};

/** Для сравнения: без выделения звёздочками, тире любого вида — дефис, пробелы одинарные, «ё» = «е». */
const norm = (s: string) =>
  String(s || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[*_]/g, "")
    .replace(/[  ]/g, " ")
    .replace(/\s*[—–-]\s*/g, " - ")
    .replace(/^\s*[•·▪]\s*/gm, "")
    .replace(/\s+/g, " ")
    .trim();

const latinWords = (text: string): string[] => {
  const out: string[] = [];
  for (const m of text.matchAll(LATIN)) {
    const v = norm(m[0]).replace(/[.'’-]+$/g, "");
    if (v.length >= 3 && !NOT_A_VARIETY.has(v)) out.push(v);
  }
  return out;
};

export interface ProgramFacts {
  /** Цены из черновика — цифрами: «180», «1250». */
  prices: string[];
  /** Количества из черновика («от 300 шт.», «в прошлый раз 200 шт.») — их модель может повторить. */
  quantities: string[];
  /** Строки-позиции для сравнения (без значка, звёздочек и регистра) — они обязаны дойти дословно. */
  lines: string[];
  /** Они же, как написаны в черновике, — так их показываем модели в замечании. */
  rawLines: string[];
  /** Всё, что в черновике написано латиницей (сорта), в нижнем регистре. */
  latin: string[];
  /** Программа сказала, что срез сегодняшний или вчерашний. */
  cutDay: boolean;
}

/** Что в черновике нельзя потерять и нельзя выдумать. */
export function programFacts(program: string): ProgramFacts {
  const text = String(program || "");
  const rawLines = text.split("\n").filter((l) => BULLET.test(l) && norm(l)).map((l) => l.trim());
  const lines = rawLines.map(norm);
  return {
    prices: Array.from(new Set(allMatches(PRICE, text))),
    quantities: Array.from(new Set(allMatches(QTY, text))),
    lines,
    rawLines,
    latin: Array.from(new Set(latinWords(text))),
    cutDay: /срез(?:ка|ан[аоы]?)?:?\s+(?:сегодня|вчера)|(?:сегодняшн|вчерашн)\S*\s+срез/iu.test(text),
  };
}

