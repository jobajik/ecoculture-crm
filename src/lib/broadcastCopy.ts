export const COPY_SCENARIOS = ["FRESH_CUT", "ALMOST_GONE", "WHO_WE_ARE", "HOLIDAY_PREORDER", "HOLIDAY_LAST_CHANCE"] as const;
export type CopyScenario = (typeof COPY_SCENARIOS)[number];
export const COPY_SEGMENTS = ["MANAGERS", "COMMON"] as const;
export type CopySegment = (typeof COPY_SEGMENTS)[number];
export const COPY_SENDERS = ["MAIN", "MANAGER", "REGIONAL"] as const;
export type CopySender = (typeof COPY_SENDERS)[number];

export interface CopySpec {
  scenario: CopyScenario;
  segment: CopySegment;
  sender: CopySender;
}

export const copySpecValue = (s: CopySpec) => `${s.scenario}|${s.segment}|${s.sender}`;

/** Метка из таблицы. Пустая или незнакомая — null: текст уходит как есть (ошибка в таблице не должна включать ИИ). */
export function parseCopySpec(raw: string | null | undefined): CopySpec | null {
  const [scenario, segment, sender] = String(raw || "").trim().toUpperCase().split("|");
  if (!(COPY_SCENARIOS as readonly string[]).includes(scenario)) return null;
  if (!(COPY_SEGMENTS as readonly string[]).includes(segment)) return null;
  if (!(COPY_SENDERS as readonly string[]).includes(sender)) return null;
  return { scenario: scenario as CopyScenario, segment: segment as CopySegment, sender: sender as CopySender };
}

/** Метка после отправки: кто написал текст. «…|ai» — копирайтер; «…|program: причина» — ушёл черновик программы. */
export function copyDone(spec: CopySpec, by: "ai" | "program", problems: string[] = []): string {
  const why = problems.join("; ").replace(/\|/g, "/").slice(0, 160);
  return `${copySpecValue(spec)}|${by}${by === "program" && why ? `: ${why}` : ""}`;
}

/** Что записано в метке после отправки. `by` пусто — сообщение ещё не уходило (в `Text` лежит черновик). */
export function copyOutcome(raw: string | null | undefined): { by: "" | "ai" | "program"; why: string } {
  const tail = String(raw || "").split("|").slice(3).join("|").trim();
  if (tail === "ai") return { by: "ai", why: "" };
  if (tail.startsWith("program")) return { by: "program", why: tail.replace(/^program:?\s*/, "") };
  return { by: "", why: "" };
}

