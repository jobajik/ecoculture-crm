const SEGMENT_NOTE: Record<CopySegment, string> = {
  MANAGERS: "клиент менеджера / постоянник / активный за 60 дней",
  COMMON: "общая база / давно не брал / не покупал",
};
const SENDER_NOTE: Record<CopySender, string> = {
  MAIN: "основной номер Ecoculture",
  MANAGER: "номер менеджера — пишет он сам, от первого лица; как он представился в черновике, так и оставь",
  REGIONAL: "региональный формат — цветок едет ближайшей фурой; день фуры — в черновике",
};

/**
 * Запрос модели: данные программы и только они. Черновик — уже готовое сообщение кода (с ценами и позициями); имя
 * подставлено. Строка про «СТОП» сюда не попадает — её добавляет программа после (`splitOptOut`).
 */
export function copyUserMessage(input: {
  spec: CopySpec;
  name: string;
  program: string;
  /** «вторник, 24.11.2026» — чтобы «завтра» и «к 13–15 декабря» считались от сегодняшнего дня. */
  today: string;
  /** Что уже ушло другим получателям — заход и призыв не повторять. */
  avoid?: string[];
  /** Замечания к прошлой попытке (`checkCopy`). */
  problems?: string[];
}): string {
  const facts = programFacts(input.program);
  const lines = [
    `Имя клиента: ${input.name || "(пусто — обращайся без имени)"}`,
    `Сегмент: ${input.spec.segment} (${SEGMENT_NOTE[input.spec.segment]})`,
    `Отправитель: ${input.spec.sender} (${SENDER_NOTE[input.spec.sender]})`,
    `Сценарий: ${input.spec.scenario}`,
    `Сегодня: ${input.today}`,
    "",
    "Данные от программы — черновик сообщения. Перепиши его своими словами: другой заход, другой порядок фраз, другой призыв.",
    facts.lines.length
      ? "Строки позиций («• …») перенеси ДОСЛОВНО, каждую отдельной строкой: сорт, длина или категория и цена — знак в знак. Новых позиций не добавляй."
      : "Позиций и цен программа не передала — не называй ни сортов, ни цен.",
    facts.cutDay
      ? "День срезки — как в черновике."
      : "День срезки программа не передала: пиши «свежий срез» без «сегодня» и «вчера».",
    "Когда следующая срезка, программа не знает — про неё не пиши. Про доставку и фуру — только то, что есть в черновике.",
    ...(isHoliday(input.spec.scenario) ? ["Уточнение программы: выходной — только 16 декабря, про 17 декабря не пиши."] : []),
    "Не длиннее 600 знаков.",
    "---",
    input.program.trim(),
    "---",
  ];
  const avoid = (input.avoid ?? []).map((a) => a.trim()).filter(Boolean).slice(-3);
  if (avoid.length) {
    lines.push("", "Уже отправлено другим клиентам сегодня — начни иначе и возьми другой призыв в конце:");
    avoid.forEach((a, i) => lines.push(`${i + 1}) ${a.replace(/\s+/g, " ").slice(0, 260)}`));
  }
  if (input.problems?.length) {
    lines.push("", "В прошлой попытке было не так — исправь:", ...input.problems.slice(0, 6).map((p) => `- ${p}`));
  }
  return lines.join("\n");
}

/** Отделить строку «Чтобы не получать… ответьте СТОП» от черновика: модели она не идёт, после неё — возвращается. */
export function splitOptOut(program: string, optOutLine: string): { body: string; optOut: boolean } {
  const text = String(program || "");
  if (!text.includes(optOutLine)) return { body: text.trim(), optOut: false };
  return { body: text.replace(optOutLine, "").replace(/\n{3,}/g, "\n\n").trim(), optOut: true };
}

/** Привести ответ модели к виду сообщения: без кавычек вокруг и лишних пустых строк. */
export function cleanCopy(raw: unknown): string {
  let t = typeof raw === "string" ? raw : "";
  t = t.replace(/\r/g, "").trim();
  if (/^["«“][\s\S]*["»”]$/.test(t) && !/["«“]/.test(t.slice(1, -1))) t = t.slice(1, -1).trim();
  return t.replace(/\n{3,}/g, "\n\n");
}

/** Начало и конец сообщения — этого хватает, чтобы следующему написать иначе. */
export function copyGist(text: string, optOutLine = ""): string {
  const t = String(text || "").replace(optOutLine, "").replace(/\s+/g, " ").trim();
  if (t.length <= 200) return t;
  return `${t.slice(0, 90)} … ${t.slice(-100)}`;
}

// --- Какой сценарий у какой рассылки -----------------------------------------------------------------------

/** Клиент «активный за 60 дней» — сегмент менеджеров; остальные — общая база (слова владельца в промпте). */
export const COPY_ACTIVE_DAYS = 60;

export function segmentByLastOrder(lastOrderDay: string, today: string): CopySegment {
  if (!lastOrderDay) return "COMMON";
  const days = Math.round((Date.parse(`${today}T00:00:00Z`) - Date.parse(`${lastOrderDay}T00:00:00Z`)) / 86400000);
  return days <= COPY_ACTIVE_DAYS ? "MANAGERS" : "COMMON";
}

/** Отправитель по номеру рассылки: основной — MAIN, номер менеджера или Земфиры — MANAGER, у регионального — REGIONAL. */
export function senderOf(line: string, regional: boolean): CopySender {
  if (regional) return "REGIONAL";
  return line ? "MANAGER" : "MAIN";
}

/** «среда, 16.12» — день недели для 16 декабря этого года (в подсказке и черновике праздника). */
export function holidayFacts(year: number): { dayLabel: string } {
  const names = ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"];
  return { dayLabel: names[new Date(Date.UTC(year, 11, 16)).getUTCDay()] };
}

