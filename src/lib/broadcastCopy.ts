export const COPY_MAX_CHARS = 700;
const SPAM = /(?:^|[^а-яё])(акци[яиюей]|скидк[аиуое]|скидок|срочно|успей(?:те)?|распродаж[аиуе])(?![а-яё])/iu;
const EMOJI = /\p{Extended_Pictographic}/gu;
/** Слово капсом от четырёх букв («СВЕЖИЙ СРЕЗ»); латиница не в счёт — так пишутся сорта и «WhatsApp». */
const CAPS = /(?:^|[^А-ЯЁа-яё])([А-ЯЁ]{4,})(?![а-яё])/u;
const HOLIDAY = /16\s*декабря|день\S*\s+независимости/iu;
const isHoliday = (s: CopyScenario) => s === "HOLIDAY_PREORDER" || s === "HOLIDAY_LAST_CHANCE";

/**
 * Что не так с текстом модели. Пустой список — можно отправлять. Каждое замечание — фраза, которую можно вернуть
 * модели для второй попытки.
 */
export function checkCopy(text: string, input: { program: string; name: string; spec: CopySpec }): string[] {
  const t = String(text || "").trim();
  const out: string[] = [];
  if (!t) return ["пустой текст"];
  const facts = programFacts(input.program);
  const low = norm(t);

  // 1. Позиции и цены — ровно те, что дала программа.
  facts.lines.forEach((line, i) => {
    if (!low.includes(line)) out.push(`строка позиции изменена или потеряна — перенеси дословно: ${facts.rawLines[i]}`);
  });
  for (const line of t.split("\n").filter((l) => /^\s*[•·▪]\s+\S/.test(l)).map(norm)) {
    if (!facts.lines.includes(line)) out.push(`строки «${line.slice(0, 60)}» нет в данных программы — убери её`);
  }
  const prices = allMatches(PRICE, t);
  for (const p of facts.prices) if (!prices.includes(p)) out.push(`потеряна цена ${p} ₸ — перенеси её как в черновике`);
  for (const p of prices) if (!facts.prices.includes(p)) out.push(`цены ${p} ₸ нет в данных программы — убери её`);
  if (facts.prices.length === 0 && /₸|тенге|(?:^|[^а-яё])тг(?![а-яё])/iu.test(t)) out.push("цен в данных программы нет — не называй цены");
  const known = norm(input.program);
  for (const w of latinWords(t)) if (!known.includes(w)) out.push(`«${w}» нет в данных программы — сорта и названия не придумывай`);

  // 2. Точные остатки. Количество допустимо, только если оно было в черновике («от 300 шт.», «брали 200 шт.»).
  for (const q of allMatches(QTY, t)) if (!facts.quantities.includes(q)) out.push(`«${q} шт.» — точные количества и остатки не пишем, скажи словами`);
  if (/(?:остал[оа]сь|остаток|остатк\S*|в наличии|на складе)\s+(?:всего\s+|около\s+|примерно\s+|по\s+)?\d/iu.test(t)) out.push("точный остаток цифрой — нельзя, скажи «осталось немного»");

  // 3. Призыв в конце: вопрос или просьба написать.
  const tail = t.slice(-220);
  if (!/\?/.test(tail) && !/напишите|ответьте|дайте знать|сообщите/iu.test(tail)) out.push("в конце нет вопроса или призыва к действию");

  // 5. Человечность.
  if (t.length > COPY_MAX_CHARS) out.push(`слишком длинно (${t.length} знаков) — уложись в ${COPY_MAX_CHARS}`);
  if ((t.match(EMOJI) ?? []).length > 2) out.push("больше двух эмодзи");
  if (SPAM.test(t)) out.push("спам-слова («акция», «скидки», «срочно», «успей», «распродажа») — убери");
  if (CAPS.test(t)) out.push("слова капсом — убери");
  if (/(?:^|[^а-яё])стоп(?![а-яё])/iu.test(t)) out.push("про «СТОП» не пиши — эту строку программа добавляет сама");
  if (/\{\s*имя\s*\}/iu.test(t)) out.push("в тексте осталось «{имя}» — подставь имя или обойдись без него");
  if (!input.name && /уважаем/iu.test(t)) out.push("имени нет — без «уважаемый»");
  if (/^["«“]/.test(t) && /["»”]$/.test(t) && !/["«“]/.test(t.slice(1, -1))) out.push("текст в кавычках — убери кавычки");
  if (/(?:^|[^A-Za-z_])(MANAGERS|COMMON|FRESH_CUT|ALMOST_GONE|WHO_WE_ARE|HOLIDAY_[A-Z_]+|REGIONAL|CTA)(?![A-Za-z_])/.test(t)) out.push("в тексте служебные слова");
  if (/[#]|\*\*/.test(t)) out.push("без # и двойных звёздочек");

  // Факты, которых программа не давала.
  if (!facts.cutDay && /(?:сегодняшн|вчерашн)\S*\s+срез|срез\S*\s+(?:сегодня|вчера)|(?:сегодня|вчера)\s+(?:\S+\s+)?срез/iu.test(t)) {
    out.push("день срезки программа не называла — пиши «свежий срез» без «сегодня» и «вчера»");
  }
  if (/следующ\S+\s+срез|срез\S*\s+(?:будет\s+)?не\s*скоро|нов\S+\s+срез\S*\s+(?:будет\s+)?(?:через|не\s*скоро)/iu.test(t) && !/следующ\S+\s+срез/iu.test(input.program)) {
    out.push("когда следующая срезка, программа не знает — про неё не пиши");
  }
  if (!isHoliday(input.spec.scenario) && HOLIDAY.test(t) && !HOLIDAY.test(input.program)) out.push("про 16 декабря в данных нет — не упоминай");
  if (/17\s*декабря|16\s*[-–—и,]\s*17/iu.test(t) && !/17\s*декабря|16\s*[-–—и,]\s*17/iu.test(input.program)) out.push("выходной только 16 декабря — про 17-е не пиши");
  if (input.spec.sender !== "REGIONAL" && /фур[аоуые]/iu.test(t) && !/фур[аоуые]/iu.test(input.program)) out.push("про фуру в данных нет — не упоминай");
  return Array.from(new Set(out));
}

