/**
 * Клиент закрыл разговор — больше ему не пишем (21.10.2026, Земфира: «бот пишет клиентам, которые ранее
 * сообщили, что им неактуально — для себя, саженцы; диалог закрыт»). Одна чистая функция на два места:
 * автопилот «Дожим лидов» такого лида пропускает, помощник на номере молчит. Ошибиться «в плюс» (посчитать
 * отказом то, что им не было) стоит дешевле, чем написать отказавшемуся ещё раз, — поэтому короткая
 * фраза с «не надо» считается отказом, а в длинном сообщении «не надо» может быть про доставку.
 */

// Явный отказ или «не наш клиент» — в любом сообщении.
const STRONG = [
  /не\s*актуальн/i,
  /не\s*интерес/i,
  /неинтерес/i,
  /передумал/i,
  /отказыва/i,
  /для\s+себя/i,
  /себе\s+(нужно|надо|хотел|брал|беру)/i,
  /саженц/i,
  /рассад/i,
  /семен|семян/i,
  /с\s+корн|корням|корневищ/i,
  /горшеч|горшк|горшоч/i,
  /не\s+занимаюсь/i,
  /не\s+пишите/i,
  /не\s+беспокойте/i,
  /не\s+звоните/i,
  /отстань/i,
  /удалите\s+(мой\s+)?номер/i,
  /ошиблись|не\s+тот\s+номер|не\s+туда/i,
  /^\s*стоп\s*[.!]*\s*$/i,
  // Казахский: «не нужно», «с корнями / для посадки», «для себя / домой».
  /керек\s*емес|қажет\s*емес|керегі\s*жоқ|қажеті\s*жоқ/i,
  /тамыр/i,
  /егуге|отырғыз|көшет/i,
  /өзіме|үйге\s+(керек|алам)/i,
];

// Короткий ответ, который сам по себе и есть отказ.
const SHORT = [
  /не\s*надо|ненадо/i,
  /не\s*нужн|ненужн/i,
  /не\s*требуется/i,
  /нет[,.!\s]*спасибо/i,
  /спасибо[,.!\s]*(нет|не\s*надо|ненадо|не\s*нужно)/i,
  /^(все|всё)[,\s]*спасибо/i,
  /жоқ[,.!\s]*рахмет|рахмет[,.!\s]*жоқ/i,
];

const SHORT_MAX = 60;

/** Похоже ли сообщение клиента на отказ («неактуально», «для себя», «саженцы нужны», короткое «не надо»). */
export function looksLikeRefusal(text: string | null | undefined): boolean {
  const t = String(text || "").trim();
  if (!t) return false;
  if (STRONG.some((re) => re.test(t))) return true;
  return t.length <= SHORT_MAX && SHORT.some((re) => re.test(t));
}
