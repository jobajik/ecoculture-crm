import { MONEY_EPSILON } from "./constants";
import { hasNoClientInvoice, isConsignment, isRegionOrder } from "./orderKind";

/**
 * Готовность заявки к отгрузке — одно правило на всю программу.
 *
 * Порядок в хозяйстве такой: менеджер согласовал заявку с клиентом и поставил
 * свою галочку, бухгалтер увидел деньги и провёл оплату, и только после этого
 * зав. складом собирает и отгружает. До этого заявка у неё висит в списке —
 * чтобы она знала, что готовится, — но отгрузить её нельзя.
 *
 * Раньше проверки не было нигде: кнопка «Отгрузить» стояла на новой, никем не
 * подтверждённой и неоплаченной заявке, и сервер такую отгрузку принимал. Это
 * значит, что цветок мог уехать к клиенту раньше денег.
 *
 * Правило живёт в одном файле, потому что спрашивают о нём в четырёх местах:
 * страница заявки, список склада, страница отгрузки и серверное действие.
 * Разъедься эти проверки по местам — рано или поздно одна отстанет, и дыра
 * вернётся именно там.
 *
 * У ЗАЯВКИ БЕЗ СЧЁТА КЛИЕНТУ галочка одна. Таких случая два: перемещение в наш
 * магазин и оптовый объём на город. Счёта нет ни там, ни там — своему магазину
 * его не выставляют, а городу выставлять некому: клиента у такой заявки нет.
 * Вторая галочка ждала бы оплаты, которой по этому счёту никогда не будет:
 * заявка зависла бы навсегда, а бухгалтер каждый день закрывала бы
 * несуществующие платежи, лишь бы её расшевелить.
 *
 * Отгрузку разрешает тот, кто заявку составил: менеджер розницы или РОП.
 * Деньги по городской заявке приходят потом и с другой стороны — бухгалтер
 * вписывает поступившую сумму, и к готовности это отношения не имеет.
 */

export interface ShipGateOrder {
  /** Статус заявки: отменённую и отгруженную целиком собирать нельзя. */
  status?: string;
  managerConfirmed: boolean;
  paid: boolean;
  paidAmount: number;
  totalAmount: number;
  /** Направление собственной розницы; пусто — обычная продажа наружу. */
  retail?: string;
  /** Вид заявки: «region» — оптовый объём на город, счёта по нему нет. */
  kind?: string;
  /** Направление: по нему узнаётся заявка на реализацию (пожарка). */
  direction?: string;
  /** Условия оплаты из карточки клиента — по ним отгрузка бывает в долг. */
  clientPaymentTerms?: string;
}

/**
 * Условия, при которых цветок уезжает РАНЬШЕ денег: «По факту» (платит при
 * получении) и любая «Отсрочка N дней». Решение владельца.
 *
 * Зачем. Правило «сначала деньги» держало такие заявки в «ждут» навсегда:
 * клиенту с отсрочкой цветок отдают, а программа не давала нажать
 * «Отгрузить». Зав. складом Rose Farm: «пока „отгрузить“ не нажимаешь, со
 * склада не отнимается» — на тот день 16 заявок с прошедшей доставкой висели
 * в «ждут оплаты», а их стебли числились на складе.
 *
 * «Предоплата» и пустые условия — как раньше, деньги вперёд: пустая ячейка
 * ничего не разрешает (грабли 1.10).
 */
export function isCreditTerms(terms: string | null | undefined): boolean {
  const t = String(terms ?? "").trim().toLowerCase();
  return t === "по факту" || t.startsWith("отсрочка");
}

/** Отгрузка идёт в долг: оплаты ещё нет, но условия клиента это позволяют. */
export function shipsOnCredit(order: ShipGateOrder): boolean {
  return waitsForMoney(order) && !order.paid && isCreditTerms(order.clientPaymentTerms);
}

/**
 * Пометка для зав. складом у заявки, которую можно отгрузить без оплаты:
 * «в долг · Отсрочка 7 дней». Пусто — если оплата есть или не нужна.
 */
export function creditNote(order: ShipGateOrder): string {
  return shipsOnCredit(order) ? `в долг · ${String(order.clientPaymentTerms).trim()}` : "";
}

/**
 * Ждёт ли отгрузка денег. Не ждёт у заявок без счёта (наш магазин, город) и у
 * заявок НА РЕАЛИЗАЦИЮ: пожарка платит за то, что продала, — то есть уже ПОСЛЕ
 * того, как цветок уехал. Потребуй здесь оплату, и такую заявку не отгрузили бы
 * никогда.
 */
function waitsForMoney(order: ShipGateOrder): boolean {
  return !hasNoClientInvoice(order) && !isConsignment(order);
}

/** Заявку можно отгружать. */
export function isReadyToShip(order: ShipGateOrder): boolean {
  // Отменённую не собирают, даже если галочки остались: вкладка склада,
  // открытая до отмены, иначе отгрузила бы её (аудит сентября).
  if (order.status === "cancelled" || order.status === "shipped") return false;
  if (!order.managerConfirmed) return false;
  if (!waitsForMoney(order)) return true;
  return order.paid || isCreditTerms(order.clientPaymentTerms);
}

/**
 * Чего именно не хватает — короткими кусками, чтобы собрать фразу.
 * Пустой список означает, что заявка готова.
 */
export function missingForShip(order: ShipGateOrder): string[] {
  const missing: string[] = [];
  if (!order.managerConfirmed) {
    // Слова разные, потому что читают их разные люди: зав. складом должна
    // понимать, кого ждать. У магазина это менеджер розницы, у города — РОП.
    missing.push(
      isRegionOrder(order)
        ? "подтверждения объёма"
        : (order.retail || "").trim()
          ? "подтверждения менеджера розницы"
          : "подтверждения менеджера"
    );
  }
  // Своему магазину счёт не выставляют — оплату здесь не ждут вовсе.
  if (waitsForMoney(order) && !order.paid && !isCreditTerms(order.clientPaymentTerms)) {
    const rest = order.totalAmount - order.paidAmount;
    // Частичная оплата — это тоже «не оплачено», но зав. складом полезно
    // видеть, что деньги уже идут, а не думать, что клиент молчит.
    missing.push(
      order.paidAmount > MONEY_EPSILON && rest > MONEY_EPSILON
        ? `остатка оплаты ${Math.round(rest).toLocaleString("ru-RU")} ₸`
        : "оплаты"
    );
  }
  return missing;
}

/**
 * Готовая фраза для человека: «Ждёт подтверждения менеджера и оплаты».
 * Для готовой заявки возвращает пустую строку.
 */
export function notReadyReason(order: ShipGateOrder): string {
  if (order.status === "cancelled") return "Заявка отменена";
  if (order.status === "shipped") return "Заявка уже отгружена";
  const missing = missingForShip(order);
  if (missing.length === 0) return "";
  return `Ждёт ${missing.join(" и ")}`;
}
