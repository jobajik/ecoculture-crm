/**
 * Что именно уходит в ячейку Google-таблицы.
 *
 * Беда, ради которой этот файл появился. Владелец прислал снимок заявки, где
 * вместо телефона клиента стоит **#ERROR!**, и той же надписью испорчена фраза
 * про Kaspi. Никакой ошибки в программе при этом нет: телефон записан как
 * «+7 701 555 20 30», а Google-таблица, получая значение, начинающееся с плюса,
 * считает его НАЧАЛОМ ФОРМУЛЫ — дописывает знак равенства, пытается сосчитать
 * «+7 701 555 20 30» как выражение и, разумеется, не может. В ячейке остаётся
 * `#ERROR!`, и обратно программа читает уже её: телефон потерян.
 *
 * Это та же природа, что у граблей 1.9-bis: таблица отдаёт не то, что мы
 * записали, а то, во что она это превратила. Там она превращала дату в число,
 * здесь — текст в формулу.
 *
 * Формулой Google считает значение, начинающееся с `=`, `+`, `-` или `@`.
 * Правило поэтому простое: **любая СТРОКА с таким началом помечается ведущим
 * апострофом.** Для Google апостроф означает «это текст, не считай»; он не
 * часть значения, в ячейке его не видно, и при чтении он не возвращается.
 *
 * Соблазн был сделать умнее — пропускать то, что «похоже на число», чтобы
 * «-5» доехало числом. От него пришлось отказаться, и вот почему: телефон
 * «+77015552030», написанный без пробелов, — совершенно законное число с точки
 * зрения любой такой проверки. Он доехал бы числом 77015552030, потеряв плюс, и
 * это было бы ровно той же потерей, от которой файл защищает, только тихой.
 *
 * Числам от этого правила ни холодно ни жарко: они приходят сюда числами, а не
 * строками (см. `toCell()`), и до этой функции не доходят вовсе. А значит, и
 * формулы владельца в самой таблице (СУММ по колонке) продолжают считать.
 *
 * Функция чистая и покрыта `scripts/check-sheet-cell.ts`. Применяется в ОДНОМ
 * месте — `toCell()` в `sheets.ts`, через которое проходит каждая запись.
 */

/** Начала, после которых Google-таблица считает значение формулой. */
const FORMULA_STARTS = ["=", "+", "-", "@"];

/**
 * Строка в том виде, в каком её можно отдать таблице, не потеряв.
 *
 * Возвращает либо саму строку, либо её же с ведущим апострофом — знаком «это
 * текст». Ничего не обрезает и не переписывает: значение должно доехать до
 * ячейки ровно таким, каким его ввёл человек.
 */
export function sheetSafeText(value: string): string {
  if (!value) return value;
  return FORMULA_STARTS.includes(value[0]) ? `'${value}` : value;
}

/** Значения, которыми таблица сообщает о своей ошибке в ячейке. */
export const SHEET_ERROR_VALUES = [
  "#ERROR!",
  "#VALUE!",
  "#REF!",
  "#NAME?",
  "#N/A",
  "#DIV/0!",
  "#NUM!",
  "#NULL!",
];

/** Ячейка сломана — в ней не данные, а жалоба таблицы. */
export function isSheetError(value: string | null | undefined): boolean {
  return SHEET_ERROR_VALUES.includes(String(value ?? "").trim().toUpperCase());
}

/**
 * Жалоба таблицы ВНУТРИ значения, а не вместо него.
 *
 * Так выглядит вторая беда, посерьёзнее первой: программа прочитала сломанную
 * ячейку, получила «#ERROR!» и записала это дальше как обычный текст — скажем,
 * в телефон заявки, который копируется из карточки клиента. Вышло
 * «#ERROR! ()». Восстанавливать тут нечего: настоящее значение потеряли ещё до
 * этой записи, и единственный честный ответ — пустая ячейка.
 *
 * Я на этом уже обжёгся: первая починка таких значений не распознала и записала
 * строку «#ERROR! ()» в двадцать ячеек живой базы. Не разрушительно (там и так
 * была жалоба), но в таблице остаётся мусор, выглядящий как вечная поломка.
 */
export function containsSheetError(value: string | null | undefined): boolean {
  const text = String(value ?? "").toUpperCase();
  return SHEET_ERROR_VALUES.some((marker) => text.includes(marker));
}

/**
 * Что человек написал в ячейке, которая теперь показывает ошибку.
 *
 * Само значение потеряно — читая ячейку, мы получаем `#ERROR!`. Но исходная
 * запись цела: таблица хранит её как ФОРМУЛУ, и Google отдаёт её, если
 * попросить `valueRenderOption: "FORMULA"`. Из `=+7 701 555 20 30` восстановить
 * «+7 701 555 20 30» — значит вернуть телефон, а не придумать его заново.
 *
 * Пустая строка означает «восстановить нечем»: ошибка в ячейке не от нашей
 * записи, и трогать её нельзя.
 */
export function recoverFromFormula(formula: string | null | undefined): string {
  const raw = String(formula ?? "");
  if (!raw.trim()) return "";
  // Бывает, что таблица отдаёт ту же жалобу и здесь — тогда восстанавливать
  // нечем, и ячейку надо оставить в покое, а не записывать в неё «#ERROR!».
  if (isSheetError(raw)) return "";
  // Ведущий знак равенства может быть, а может и не быть. Первая версия этого
  // файла требовала его обязательно — и не починила НИ ОДНОЙ из 62 ячеек на
  // боевой базе: Google отдаёт такую запись ровно в том виде, в каком её
  // ввели, то есть «+7 701 555 20 30», без знака равенства. Урок тот же, что и
  // всегда: проверять надо на живых данных, а не на своём представлении о них.
  const body = raw.startsWith("=") ? raw.slice(1) : raw;
  if (!body.trim()) return "";
  // Жалоба таблицы ВНУТРИ значения («#ERROR! ()») — значит настоящее значение
  // потеряли ещё раньше, и восстанавливать нечего.
  if (containsSheetError(body)) return "";
  // Настоящую формулу (с функцией или ссылкой на ячейку) не трогаем: её писал
  // человек, и превратить её в текст значило бы сломать его расчёт.
  if (/[A-Za-zА-Яа-я]+\s*\(/.test(body)) return "";
  if (/^[A-Z]{1,3}\$?\d+/.test(body.trim())) return "";
  return body;
}
