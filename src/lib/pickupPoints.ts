/** Город к виду для сравнения: регистр, «ё», «г.» впереди, дефисы и лишние пробелы, точка в конце. */
export function pickupCityKey(raw: string | null | undefined): string {
  return String(raw ?? "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .trim()
    .replace(/^г\.\s*|^г\s+|^город\s+/, "")
    .replace(/[\s-]+/g, " ")
    .replace(/[.,;]+$/, "")
    .trim();
}

/** Склад для самовывоза в городе клиента; города нет в списке — null. */
export function pickupPointFor(city: string | null | undefined): PickupPoint | null {
  const key = pickupCityKey(city);
  if (!key) return null;
  return PICKUP_POINTS.find((p) => p.aliases.includes(key)) ?? null;
}

