import { ROLES } from "./constants";

/**
 * Кнопка «новая заявка» в списке заявок: кому она положена и куда ведёт.
 *
 * Владелец спросил: «Почему у РОПа нет возможности оформлять заявку на регионы
 * по опту?» Возможность была — форма объёма на город работает, — но попасть в
 * неё можно было только одним путём: «Планы» → «Регионы» → «+ Объём в регион».
 * В разделе «Заявки», то есть ровно там, где все остальные заводят заявки, у
 * РОПа кнопки не было вовсе. Со стороны это и значит «нельзя»: человек пришёл в
 * заявки, кнопки нет, вывод сделан.
 *
 * Урок не про кнопку. **Возможность, о которой нельзя догадаться, ничем не
 * отличается от отсутствующей.** Проверять надо не «работает ли действие», а
 * «найдёт ли его человек оттуда, откуда он придёт».
 *
 * Поэтому правило одно и живёт здесь:
 *
 * - **менеджер, администратор и менеджеры розницы** заводят обычную заявку;
 * - **РОП** заводит и обычную заявку клиенту (02.10.2026, РОП: «добавь мне
 *   возможность забивать заявки не только на регион — надо забить заявку
 *   Бахтияра»; в форме он выбирает, на какого менеджера её записать), и объём на
 *   город — второй кнопкой (`newOrderLinksFor`);
 * - **зав. складом** заводит здесь опт на город своим цветком («+ Опт в
 *   регион»); заявки в наши магазины регионов — в «Рознице — регионы»;
 * - **бухгалтеру и агроному** заводить нечего.
 *
 * Функция чистая и покрыта `scripts/check-region-orders.ts`.
 */
export interface NewOrderLink {
  href: string;
  label: string;
}

export function newOrderLinkFor(role: string | null | undefined): NewOrderLink | null {
  switch (role) {
    case ROLES.MANAGER:
    case ROLES.ADMIN:
    case ROLES.RETAIL_ALMATY:
    case ROLES.RETAIL_REGIONS:
    case ROLES.OFFICE_RETAIL:
      return { href: "/orders/new", label: "+ Новая заявка" };
    case ROLES.SALES_HEAD:
      return { href: "/orders/new", label: "+ Новая заявка" };
    case ROLES.WAREHOUSE:
      // Зав. складом заводит опт на город своим цветком (решение владельца).
      // Заявки в наши магазины регионов — по-прежнему в «Рознице — регионы».
      return { href: "/orders/new?region=1", label: "+ Опт в регион" };
    default:
      return null;
  }
}

/**
 * Все кнопки «новая заявка» в разделе «Заявки»: основная первой. У РОПа их две —
 * заявка клиенту и объём на город.
 */
export function newOrderLinksFor(role: string | null | undefined): NewOrderLink[] {
  const main = newOrderLinkFor(role);
  if (!main) return [];
  if (role === ROLES.SALES_HEAD) return [main, { href: "/orders/new?region=1", label: "+ Объём в регион" }];
  return [main];
}
