/**
 * Какую роль оставить в пропуске сотрудника при очередной проверке.
 *
 * Беда, ради которой файл появился. Владелец прислал снимок: у бухгалтера Юлии
 * в списке оплат вместо кнопки «Оплата» стоит слово «просмотр» — то есть
 * программа считает, что прав у неё нет. При этом на страницу `/finance` её
 * пустили, а пускает туда только бухгалтера и администратора. Одно противоречит
 * другому, и объяснение оказалось неприятным.
 *
 * Роль лежит в пропуске (токене), но **при КАЖДОЙ отрисовке страницы** она
 * перечитывается из вкладки Users: так задумано, чтобы права можно было менять
 * на ходу. Охранник на входе (middleware) смотрит в сам пропуск и ничего не
 * перечитывает — поэтому он пустил. А страница спросила таблицу заново, таблица
 * в тот миг не ответила (Google отвечает не всегда: лимиты, сеть, секундная
 * недоступность), и программа сделала вывод «такого сотрудника нет» — то есть
 * обошлась с Юлией как с уволенной.
 *
 * Это и есть ошибка: **«таблица не ответила» и «сотрудника в таблице нет» — это
 * разные вещи, а программа считала их одним.** Отзывать права надо тогда, когда
 * мы ЗНАЕМ, что строки нет или она отключена, а не тогда, когда нам не удалось
 * это выяснить. Заметьте: грабли 1.10 («ошибка в таблице должна закрывать
 * доступ») этому не противоречат. Там речь про ПУСТУЮ ЯЧЕЙКУ — про прочитанные
 * данные, в которых чего-то не хватает. Здесь данных нет вовсе, и правильный
 * ответ — «не знаю», а не «уволен».
 *
 * Что при этом не ломается: снятие прав по-прежнему срабатывает при первом же
 * УДАЧНОМ чтении, то есть через несколько секунд. Уволенный не получает лазейки:
 * чтобы оставить себе доступ, ему пришлось бы непрерывно ронять Google-таблицу.
 *
 * Функция чистая и покрыта `scripts/check-auth-role.ts`.
 */

/** Что вернул поход в таблицу. Главное здесь — что «не смогли» отличимо от «нет». */
export type RoleLookup =
  | { ok: true; user: { role: string; farm: string | null; name: string; active: boolean } | null }
  | { ok: false };

export interface TokenRole {
  role: string | undefined;
  farm: string | null;
  name: string | undefined;
}

export function roleForToken(current: TokenRole, lookup: RoleLookup): TokenRole {
  // Таблица не ответила — оставляем пропуск как есть. Это не «уволен», это «не
  // знаем»; через несколько секунд перечитаем и узнаем.
  if (!lookup.ok) return current;

  const user = lookup.user;
  // Строки нет или сотрудник отключён — права снимаем. Ровно ради этого роль и
  // перечитывается: список сотрудников в таблице должен означать то, что обещает.
  if (!user || !user.active) return { role: undefined, farm: null, name: current.name };

  return {
    role: user.role,
    farm: user.farm ?? null,
    // Имя из таблицы лучше имени из Google: владелец пишет там «Юлия», а Google
    // отдаёт то, что человек когда-то ввёл себе в профиль.
    name: user.name || current.name,
  };
}
