/*
 * Текст должен доезжать до ячейки текстом.
 *
 * Владелец прислал снимок заявки, где вместо телефона клиента стоит #ERROR!.
 * Причина не в программе: телефон «+7 701 555 20 30» Google-таблица принимает
 * за начало формулы, пытается его сосчитать и оставляет в ячейке жалобу. Дальше
 * программа читает уже эту жалобу — телефон потерян совсем.
 *
 * Проверка стережёт обе стороны правила, потому что ошибиться можно в любую:
 *
 * - защитили слишком мало — вернётся #ERROR! на первом же телефоне с плюсом;
 * - защитили слишком много — числа поедут в таблицу текстом, и формулы
 *   владельца в самой таблице (СУММ по колонке) перестанут считать.
 *
 * Запуск: npx tsx scripts/check-sheet-cell.ts
 */
import {
  containsSheetError,
  isSheetError,
  recoverFromFormula,
  sheetSafeText,
} from "../src/lib/sheetCell";

let fails = 0;
function check(label: string, actual: unknown, expected: unknown) {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (!ok) fails++;
  console.log(
    `${ok ? "OK  " : "FAIL"} ${label}: ${JSON.stringify(actual)}${
      ok ? "" : ` (ждали ${JSON.stringify(expected)})`
    }`
  );
}

// --- Что защищаем ----------------------------------------------------------

check("телефон с плюсом защищён", sheetSafeText("+7 701 555 20 30"), "'+7 701 555 20 30");
check("знак равенства в начале", sheetSafeText("=привет"), "'=привет");
check("собачка в начале", sheetSafeText("@Астана"), "'@Астана");
check("минус и текст", sheetSafeText("-нет данных"), "'-нет данных");
check("тире в комментарии", sheetSafeText("— уточнить"), "— уточнить");

// --- Что НЕ трогаем --------------------------------------------------------

check("обычный текст не трогаем", sheetSafeText("Салон «Ирис»"), "Салон «Ирис»");
check("телефон без плюса не трогаем", sheetSafeText("87015552030"), "87015552030");
check("пусто остаётся пустым", sheetSafeText(""), "");
check("обычное число не трогаем", sheetSafeText("60000"), "60000");
check("дата не трогается", sheetSafeText("2026-09-14"), "2026-09-14");

// Числа приходят в таблицу ЧИСЛАМИ и до этой функции не доходят вовсе, поэтому
// формулы владельца в самой таблице продолжают считать. А строку с ведущим
// знаком защищаем всегда, даже если она выглядит числом: телефон
// «+77015552030» — законное число для любой проверки «похоже на число», и
// доехал бы он как 77015552030, потеряв плюс. Это та же потеря, только тихая.
check("телефон-число всё равно защищён", sheetSafeText("+77015552030"), "'+77015552030");
check("строка «-5» защищена, и это не беда", sheetSafeText("-5"), "'-5");

// --- Узнаём сломанную ячейку ------------------------------------------------

check("#ERROR! — это ошибка", isSheetError("#ERROR!"), true);
check("#VALUE! тоже", isSheetError("#VALUE!"), true);
check("с пробелами по краям тоже", isSheetError("  #REF!  "), true);
check("обычный текст — не ошибка", isSheetError("+7 701 555 20 30"), false);
check("пусто — не ошибка", isSheetError(""), false);

// --- Восстановление потерянного ---------------------------------------------
//
// Значение цело: таблица хранит его как формулу, и Google отдаёт её отдельным
// запросом. Из «=+7 701…» телефон восстанавливается, а не придумывается заново.

check("телефон восстановлен", recoverFromFormula("=+7 701 555 20 30"), "+7 701 555 20 30");
// Знака равенства может и не быть: на боевой базе Google отдал записи ровно
// такими, какими их ввели. Первая версия требовала «=» обязательно и не
// починила ни одной из 62 ячеек.
check("без знака равенства тоже", recoverFromFormula("+7 701 555 20 30"), "+7 701 555 20 30");
check("минус тоже", recoverFromFormula("=-нет данных"), "-нет данных");
check("жалоба вместо значения — восстанавливать нечем", recoverFromFormula("#ERROR!"), "");
// Жалоба ВНУТРИ значения: программа прочитала сломанную ячейку и записала
// «#ERROR!» дальше как обычный текст. Первая версия починки этого не заметила и
// записала строку «#ERROR! ()» в двадцать ячеек живой базы.
check("жалоба внутри значения — тоже нечем", recoverFromFormula("#ERROR! ()"), "");
check("и с равенством впереди", recoverFromFormula("=#ERROR! ()"), "");
check("узнаём жалобу внутри строки", containsSheetError("#ERROR! ()"), true);
check("обычный телефон — не жалоба", containsSheetError("+7 701 555 20 30"), false);
check("пусто — не жалоба", containsSheetError(""), false);
check("пусто — нечего", recoverFromFormula(""), "");
check("пустая формула — нечего", recoverFromFormula("=   "), "");
// Настоящую формулу владельца трогать нельзя: превратив её в текст, мы сломаем
// его собственный расчёт в таблице.
check("формулу с функцией не трогаем", recoverFromFormula("=СУММ(A1:A9)"), "");
check("английскую тоже", recoverFromFormula("=SUM(A1:A9)"), "");
check("ссылку на ячейку не трогаем", recoverFromFormula("=A1*2"), "");

// --- Круг: защитили — прочитали — то же самое -------------------------------
//
// Апостроф для Google — пометка «это текст», а не часть значения: в ячейке его
// не видно, и при чтении он не возвращается. Здесь это и проверяется.
const phone = "+7 701 555 20 30";
check("после защиты видно то же значение", sheetSafeText(phone).replace(/^'/, ""), phone);

console.log(fails === 0 ? "\nВсе проверки прошли" : `\nПровалено проверок: ${fails}`);
process.exit(fails === 0 ? 0 : 1);
