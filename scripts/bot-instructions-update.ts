import * as dotenv from "dotenv";
dotenv.config({ path: ".env.local" });
dotenv.config();

/**
 * Правка указаний бота (настройка BotInstructions) по живому разговору:
 * владелец, 02.10.2026 — клиент написал «третью категорию, одна коробка нужна»,
 * а бот выдумал «коробку на 100 шт.» и спросил «50 или 100?». «В коробке 3
 * категории — 200 штук. Продавай, без вопросов ненужных». Меняет только
 * перечисленные строки, остальное — как написал владелец. Без --yes — показ.
 *
 *   npx tsx scripts/bot-instructions-update.ts [--yes]
 */
import { settingsMap } from "../src/lib/repo/broadcasts";
import { saveSettings } from "../src/lib/repo/settings";

const EDITS: [RegExp, string][] = [
  [
    /^- Каждое сообщение заканчивай одним простым вопросом.*$/m,
    "- Каждое сообщение заканчивай одним простым вопросом к заказу — чаще всего «Оформляю?».",
  ],
  [
    /^КАК ПРОДАЁШЬ\s*$/m,
    [
      "КАК ПРОДАЁШЬ",
      "0. ГЛАВНОЕ. Клиент сам сказал, что хочет (цветок, категорию или сорт и количество или «коробку») — никаких уточняющих",
      "   вопросов и вариантов на выбор. Сразу одним сообщением: позиция, количество, цена, сумма, день — и «Оформляю?».",
      "   Сорт не назван — бери ходовой со склада в этой категории и назови его. День — сегодня, если клиент просит сегодня,",
      "   иначе завтра. Клиента нет в базе — в том же сообщении попроси название точки и город.",
    ].join("\n"),
  ],
  [/^4\. Дай выбор.*$/m, "4. Клиент не знает, что взять, — предложи одну конкретную позицию с количеством, а не варианты на выбор."],
  [
    /^- Астана, Караганда, Семей, Усть-Каменогорск.*$/m,
    "- Астана, Караганда, Семей, Усть-Каменогорск и другие города — доставку обсуждаем отдельно.",
  ],
  [
    /^- Минимальная партия.*$/m,
    "- Минимальная партия — от 50 шт. на позицию.\n- Коробка хризантемы третьей категории — 200 шт.: «коробка» третьей = 200 шт. Сколько в коробке другой позиции, не знаешь — не выдумывай, считай в штуках.",
  ],
];

async function main() {
  const map = await settingsMap(true);
  const before = map.BotInstructions || "";
  let after = before;
  for (const [re, text] of EDITS) {
    if (!re.test(after)) console.log(`не нашёл строку: ${re}`);
    after = after.replace(re, text);
  }
  if (after.length > 4000) throw new Error(`длиннее 4000 знаков: ${after.length}`);
  console.log(`было ${before.length} знаков, стало ${after.length}\n---NEW---\n${after}\n---END---`);
  if (!process.argv.includes("--yes")) return console.log("Только показ.");
  if (after === before) return console.log("Менять нечего.");
  await saveSettings({ BotInstructions: after });
  console.log("Сохранено.");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
